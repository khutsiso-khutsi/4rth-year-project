SELECT
    TABLE_NAME,
    COLUMN_NAME,
    DATA_TYPE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE
    COLUMN_NAME LIKE '%Date%'
    OR COLUMN_NAME LIKE '%Test%'
    OR COLUMN_NAME LIKE '%Category%'
    OR COLUMN_NAME LIKE '%Result%'
    OR COLUMN_NAME LIKE '%Patient%'
ORDER BY TABLE_NAME, ORDINAL_POSITION;